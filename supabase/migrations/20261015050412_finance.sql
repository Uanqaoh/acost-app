-- One personal ledger per Supabase project. Only the trusted Edge service may call
-- the dispatcher. Human/AI credentials are independent hashes, never Supabase keys.
CREATE SCHEMA qiao;
REVOKE ALL ON SCHEMA qiao FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA qiao TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA qiao REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA qiao REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA qiao REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;

CREATE FUNCTION qiao.stamp() RETURNS text LANGUAGE sql VOLATILE SECURITY INVOKER
SET search_path = pg_catalog, qiao AS $$
 SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"+00:00"')
$$;
CREATE FUNCTION qiao.fail(message text, status integer DEFAULT 400, code text DEFAULT 'invalid_request')
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, qiao AS $$
BEGIN
 RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = message,
 DETAIL = jsonb_build_object('status',status,'body',jsonb_build_object('error',code,'message',message))::text;
END $$;
CREATE FUNCTION qiao.valid_date(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER
SET search_path = pg_catalog, qiao AS $$
BEGIN
 RETURN value ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' AND to_char(value::date,'YYYY-MM-DD') = value AND left(value,4) <> '0000';
EXCEPTION WHEN OTHERS THEN RETURN false;
END $$;
CREATE FUNCTION qiao.str(value jsonb, field text, max_length integer, optional boolean DEFAULT false)
RETURNS text LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER SET search_path = pg_catalog, qiao AS $$
DECLARE result text;
BEGIN
 IF optional AND (value IS NULL OR value = 'null'::jsonb) THEN RETURN ''; END IF;
 IF jsonb_typeof(value) IS DISTINCT FROM 'string' THEN PERFORM qiao.fail(field || ' 必须是字符串'); END IF;
 result := btrim(value #>> '{}');
 IF length(result) > max_length OR (result = '' AND NOT optional) THEN PERFORM qiao.fail(field || ' 长度不正确'); END IF;
 RETURN result;
END $$;
CREATE FUNCTION qiao.integer(value jsonb, field text, minimum bigint, maximum bigint)
RETURNS bigint LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER SET search_path = pg_catalog, qiao AS $$
DECLARE result numeric;
BEGIN
 IF jsonb_typeof(value) IS DISTINCT FROM 'number' OR (value #>> '{}') !~ '^-?[0-9]+$' THEN
  PERFORM qiao.fail(field || ' 必须是整数');
 END IF;
 result := (value #>> '{}')::numeric;
 IF result < minimum OR result > maximum THEN PERFORM qiao.fail(field || ' 超出允许范围'); END IF;
 RETURN result::bigint;
END $$;
-- Python json.dumps(ensure_ascii=False, sort_keys=True, separators=(',',':'))
-- compatible for the integer/string request values accepted by this API.
CREATE FUNCTION qiao.canonical(value jsonb) RETURNS text LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER
SET search_path = pg_catalog, qiao AS $$
DECLARE result text;
BEGIN
 CASE jsonb_typeof(value)
 WHEN 'object' THEN SELECT '{' || coalesce(string_agg(to_jsonb(key)::text || ':' || qiao.canonical(val), ',' ORDER BY key COLLATE "C"),'') || '}' INTO result FROM jsonb_each(value) AS e(key,val);
 WHEN 'array' THEN SELECT '[' || coalesce(string_agg(qiao.canonical(val), ',' ORDER BY ordinal),'') || ']' INTO result FROM jsonb_array_elements(value) WITH ORDINALITY AS e(val,ordinal);
 ELSE result := value::text;
 END CASE;
 RETURN result;
END $$;

CREATE TABLE qiao.settings(key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE qiao.accounts(
 name text PRIMARY KEY CHECK (length(name) BETWEEN 1 AND 100),
 opening_balance_cents bigint NOT NULL DEFAULT 0 CHECK (opening_balance_cents BETWEEN -999999999999 AND 999999999999),
 sort_order bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE TABLE qiao.categories(
 name text PRIMARY KEY CHECK (length(name) BETWEEN 1 AND 100),
 color text NOT NULL CHECK (color ~ '^#[A-Fa-f0-9]{6}$'),
 sort_order bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE TABLE qiao.credentials(
 id text PRIMARY KEY CHECK (id ~ '^[a-f0-9]{32}$'),
 name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
 role text NOT NULL CHECK (role IN ('readonly','ai','admin')),
 token_hash text NOT NULL UNIQUE CHECK (token_hash ~ '^[a-f0-9]{64}$'),
 created_at text NOT NULL DEFAULT qiao.stamp(), revoked_at text
);
CREATE TABLE qiao.receipts(
 filename text PRIMARY KEY CHECK (filename ~ '^[a-f0-9]{32}\.(png|jpg|webp)$'),
 sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
 size bigint NOT NULL CHECK (size BETWEEN 1 AND 8388608),
 created_at text NOT NULL DEFAULT qiao.stamp(), created_by text NOT NULL CHECK (length(created_by) BETWEEN 1 AND 200)
);
CREATE TABLE qiao.entries(
 id text PRIMARY KEY CHECK (id ~ '^[a-f0-9]{32}$'),
 type text NOT NULL CHECK (type IN ('expense','income','transfer','refund')),
 amount_cents bigint NOT NULL CHECK (amount_cents BETWEEN 1 AND 999999999999),
 date text NOT NULL CHECK (qiao.valid_date(date)),
 time text NOT NULL CHECK (time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
 merchant text NOT NULL DEFAULT '' CHECK (length(merchant) <= 300),
 note text NOT NULL DEFAULT '' CHECK (length(note) <= 10000),
 category text NOT NULL DEFAULT '' CHECK (length(category) <= 100),
 account text NOT NULL REFERENCES qiao.accounts(name),
 to_account text REFERENCES qiao.accounts(name),
 original_id text REFERENCES qiao.entries(id),
 receipt_url text CHECK (receipt_url ~ '^/api/receipts/[a-f0-9]{32}\.(png|jpg|webp)$'),
 idempotency_key text UNIQUE CHECK (length(idempotency_key) BETWEEN 1 AND 200),
 request_hash text CHECK (request_hash ~ '^[a-f0-9]{64}$'),
 deleted_at text, created_at text NOT NULL, updated_at text NOT NULL,
 version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
 created_by text NOT NULL DEFAULT 'legacy' CHECK (length(created_by) BETWEEN 1 AND 200),
 updated_by text NOT NULL DEFAULT 'legacy' CHECK (length(updated_by) BETWEEN 1 AND 200),
 CHECK ((type = 'refund') = (original_id IS NOT NULL)),
 CHECK ((type = 'transfer') = (to_account IS NOT NULL)),
 CHECK (type <> 'transfer' OR (to_account <> account AND category = ''))
);
CREATE INDEX entries_active_date ON qiao.entries(date DESC,time DESC,created_at DESC,id DESC) WHERE deleted_at IS NULL;
CREATE INDEX entries_original ON qiao.entries(original_id) WHERE original_id IS NOT NULL;
CREATE INDEX entries_account ON qiao.entries(account);
CREATE INDEX entries_to_account ON qiao.entries(to_account) WHERE to_account IS NOT NULL;
CREATE TABLE qiao.audit_events(
 sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 at text NOT NULL DEFAULT qiao.stamp(), actor text NOT NULL CHECK (length(actor) BETWEEN 1 AND 200),
 action text NOT NULL, entity_id text NOT NULL, before_json jsonb, after_json jsonb
);
CREATE INDEX audit_entity ON qiao.audit_events(entity_id,sequence DESC);

